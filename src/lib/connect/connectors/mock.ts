import type {
  Connector,
  ConnectorContext,
  ConnectorResult,
  ConnectorTestResult,
  ExternalRecord,
} from "../types";

/**
 * Sandbox connector: generates deterministic records.
 *
 * It exists so the engine, job history and health surfaces can be exercised
 * (and tested) without a third-party account. It is labelled as simulated in
 * the catalogue — it must never be mistaken for a real integration.
 */

const MAX_RECORDS = 200;

function recordCount(context: ConnectorContext): number {
  const raw = Number(context.config.recordCount ?? 12);
  if (!Number.isFinite(raw)) return 12;
  return Math.min(MAX_RECORDS, Math.max(1, Math.floor(raw)));
}

function buildProducts(count: number): ExternalRecord[] {
  return Array.from({ length: count }, (_, index) => {
    const n = index + 1;
    return {
      externalId: `mock-product-${n}`,
      data: {
        id: `mock-product-${n}`,
        sku: `MOCK-P-${String(n).padStart(3, "0")}`,
        name: `Sandbox product ${n}`,
        price: 100 + n * 25,
        cost: 60 + n * 15,
        description: "Generated by the LipaPoint Connect sandbox",
        barcode: `89000000${String(n).padStart(4, "0")}`,
        category: "Sandbox",
        is_active: true,
        track_stock: true,
        low_stock_alert: 5,
      },
    };
  });
}

function buildCustomers(count: number): ExternalRecord[] {
  return Array.from({ length: count }, (_, index) => {
    const n = index + 1;
    return {
      externalId: `mock-customer-${n}`,
      data: {
        id: `mock-customer-${n}`,
        name: `Sandbox customer ${n}`,
        phone: `+254700${String(100000 + n).slice(-6)}`,
        email: `sandbox${n}@example.com`,
        address: "Nairobi, Kenya",
        notes: "Generated by the LipaPoint Connect sandbox",
      },
    };
  });
}

export const mockConnector: Connector = {
  id: "mock",

  async testConnection(): Promise<ConnectorTestResult> {
    return { ok: true, accountLabel: "Sandbox (generated data)" };
  },

  async fetchRecords(context: ConnectorContext): Promise<ConnectorResult> {
    const all =
      context.entity === "products" ? buildProducts(recordCount(context)) : buildCustomers(recordCount(context));
    const offset = Math.max(0, Number(context.cursor ?? 0) || 0);
    const page = all.slice(offset, offset + context.limit);
    const next = offset + context.limit < all.length ? String(offset + context.limit) : null;
    return { ok: true, records: page, nextCursor: next };
  },
};
